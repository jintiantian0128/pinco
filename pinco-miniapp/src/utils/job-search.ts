export const buildJobSearchPrompt = (query = '') => {
  const normalized = query.trim()
  if (normalized) {
    return `请帮我实时搜索“${normalized}”相关岗位。结合你记得的职业背景说明匹配点和缺口；只引用本次搜索返回的职位、来源和链接，明确这是待核验候选，不保证仍在招聘。没有结果就直接说没有找到，不要编造。若城市或年限会显著影响结果且我没说，再先问我一个关键问题。`
  }
  return '我想找适合自己的真实岗位。请先结合你记得的职业信息，只问我最关键的缺失条件（岗位方向、城市或工作年限）；信息足够后再实时搜索带原始来源链接的岗位，并说明匹配点和缺口。搜索无结果就直说，不要编造职位或招聘状态。'
}
